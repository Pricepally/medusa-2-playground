export const getRedstarWeightZonePrice = (weight: number, zoneIndex: number): number => {
  const weightData = redstarWeightZoneCostsData.find((data) => weight >= data.minWeight && weight <= data.maxWeight);
  if (weightData) {
    const zonePrices = weightData.zonePrices;
    if (zoneIndex >= 0 && zoneIndex < zonePrices.length) {
      return zonePrices[zoneIndex];
    }
  }

  if (weight >= 20_000 && weight <= 30_000) {
    const wData = redstarWeightZoneCostsData.find((data) => data.minWeight >= 20_100 && weight <= data.maxWeight);
    if (!wData) {
      throw new Error(`No weight zone data available for weight ${weight}`);
    }
    const zonePrices = wData.zonePrices;
    if (zoneIndex >= 0 && zoneIndex < zonePrices.length) {
      return zonePrices[zoneIndex];
    }
  }

  const maxWeight = 30000;

  if (weight > maxWeight) {
    // Try to find the entry that matches maxWeight; fall back to the last entry if not found
    const maxWeightData =
      redstarWeightZoneCostsData.find((data) => maxWeight === data.maxWeight) ??
      redstarWeightZoneCostsData[redstarWeightZoneCostsData.length - 1];

    if (!maxWeightData) {
      throw new Error('No weight zone data available to calculate price');
    }

    const zonePrices = maxWeightData.zonePrices;
    if (zoneIndex >= 0 && zoneIndex < zonePrices.length) {
      const maxWeightPrice = zonePrices[zoneIndex];
      const pricePerWeight = maxWeightPrice / maxWeight;
      const weightPrice = weight * pricePerWeight;
      return weightPrice;
    }

    throw new Error(`No price available for zoneIndex ${zoneIndex} using max weight data`);
  }

  throw new Error(`No price available for weight ${weight} and zoneIndex ${zoneIndex}`);
};
